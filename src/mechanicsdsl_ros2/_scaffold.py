"""
_scaffold.py
------------
Generate a complete, buildable ROS2 (ament_cmake) package from a compiled DSL
system.

Given a :class:`CompiledSystem`, :func:`scaffold_package` writes::

    mechanicsdsl_<system>/
      package.xml
      CMakeLists.txt
      include/<pkg>/<system>_dynamics.hpp   (N-DOF EOM, RK4, energy)
      src/<system>_node.cpp                 (rclcpp node)
      msg/SystemState.msg
      launch/<system>.launch.py             (loads config/<system>_params.yaml)
      config/<system>_params.yaml
      test/test_<system>_dynamics.cpp       (gtest: finite state, energy drift)

The node

* integrates the DSL-derived dynamics with RK4 (``substeps`` per tick),
* publishes ``SystemState`` (q, q_dot, q_ddot, energy, sim_time) on
  ``<system>/state`` and ``sensor_msgs/JointState`` on ``<system>/joint_states``
  so RViz / robot_state_publisher can consume it directly,
* accepts live parameter updates (``ros2 param set``) for every physical
  parameter, ``paused`` and ``substeps``,
* offers a ``<system>/reset`` ``std_srvs/Trigger`` service.
"""

from __future__ import annotations

import os
from string import Template
from typing import TYPE_CHECKING

from ._cppgen import params_struct_name, render_dynamics_header

if TYPE_CHECKING:
    from ._bridge import CompiledSystem


def _pkg_name(system: "CompiledSystem") -> str:
    return f"mechanicsdsl_{system.name}"


