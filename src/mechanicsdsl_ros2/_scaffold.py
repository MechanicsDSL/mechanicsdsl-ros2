_LAUNCH = Template(
    '''"""Launch the $system dynamics node with config/${system}_params.yaml."""
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch_ros.actions import Node


def generate_launch_description():
    config = os.path.join(
        get_package_share_directory("$pkg"), "config", "${system}_params.yaml"
    )
    return LaunchDescription([
        Node(
            package="$pkg",
            executable="$executable",
            name="${system}_node",
            output="screen",
            parameters=[config],
        ),
    ])
'''
)


def _render_declare_params(system: "CompiledSystem") -> str:
    return "\n".join(
        f'    p_.{name} = this->declare_parameter<double>("{name}", '
        f"{float(system.parameters[name])!r});"
        for name in sorted(system.parameters)
    )


def _render_param_updates(system: "CompiledSystem") -> str:
    return "\n".join(
        f'            else if (n == "{name}") {{ p_.{name} = prm.as_double(); }}'
        for name in sorted(system.parameters)
    )


def render_params_yaml(system: "CompiledSystem", rate_hz: float = 250.0) -> str:
    """ROS2 parameter file; ``/**`` applies it whatever the node's namespace."""
    lines = ["/**:", "  ros__parameters:", f"    rate_hz: {rate_hz!r}",
             "    substeps: 1", "    paused: false"]
    for name in sorted(system.parameters):
        lines.append(f"    {name}: {float(system.parameters[name])!r}")
    return "\n".join(lines) + "\n"


def render_launch(system: "CompiledSystem", pkg: str, executable: str) -> str:
    return _LAUNCH.substitute(system=system.name, pkg=pkg, executable=executable)


def scaffold_package(system: "CompiledSystem", out_dir: str, rate_hz: float = 250.0) -> str:
    """Write a complete ament_cmake ROS2 package for ``system`` under ``out_dir``.

    Returns the path to the generated package directory.
    """
    pkg = _pkg_name(system)
    root = os.path.join(out_dir, pkg)
    include_dir = os.path.join(root, "include", pkg)
    for sub in ("src", "msg", "launch", "config", "test", os.path.join("include", pkg)):
        os.makedirs(os.path.join(root, sub), exist_ok=True)

    cls = "".join(p.capitalize() for p in system.name.split("_"))
    subs = {
        "pkg": pkg,
        "system": system.name,
        "cls": cls,
        "up": system.name.upper(),
        "dof": str(system.dof),
        "rate": repr(float(rate_hz)),
        "params_struct": params_struct_name(system),
        "declare_params": _render_declare_params(system),
        "param_updates": _render_param_updates(system),
        "names": ", ".join(f'"{c}"' for c in system.coordinates),
        "energy_expr": ("mechanicsdsl::energy(y_.data(), p_)"
                        if system.energy is not None else "0.0"),
    }
    subs["energy_test"] = (_GTEST_ENERGY.substitute(subs)
                           if system.energy is not None and system.conservative else "")

    guard = f"MECHANICSDSL_{system.name.upper()}_DYNAMICS_HPP"
    files = {
        os.path.join(root, "package.xml"): _PACKAGE_XML.substitute(subs),
        os.path.join(root, "CMakeLists.txt"): _CMAKELISTS.substitute(subs),
        os.path.join(include_dir, f"{system.name}_dynamics.hpp"):
            render_dynamics_header(system, guard),
        os.path.join(root, "src", f"{system.name}_node.cpp"): _NODE_CPP.substitute(subs),
        os.path.join(root, "msg", "SystemState.msg"): _SYSTEM_STATE_MSG,
        os.path.join(root, "launch", f"{system.name}.launch.py"):
            render_launch(system, pkg, f"{system.name}_node"),
        os.path.join(root, "config", f"{system.name}_params.yaml"):
            render_params_yaml(system, rate_hz),
        os.path.join(root, "test", f"test_{system.name}_dynamics.cpp"):
            _GTEST.substitute(subs),
    }
    for path, content in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    return root
