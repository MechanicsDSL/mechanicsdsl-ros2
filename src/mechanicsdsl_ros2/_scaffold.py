"""
_scaffold.py
------------
Generate a complete, buildable ROS2 package from a compiled DSL system.

Given a :class:`CompiledSystem`, :func:`scaffold_package` writes a colcon-ready
package tree:

    <pkg>/
      package.xml
      CMakeLists.txt
      include/<pkg>/<system>_dynamics.hpp   (generic N-DOF EOM + RK4)
      src/<system>_node.cpp                 (rclcpp node, publishes state)
      msg/SystemState.msg
      launch/<system>.launch.py
      config/<system>_params.yaml

The dynamics header is produced by :mod:`._cppgen` directly from the symbolic
equations of motion, so the node integrates the real derived dynamics.
"""

from __future__ import annotations

import os
from string import Template
from typing import TYPE_CHECKING

from ._cppgen import params_struct_name, render_dynamics_header

if TYPE_CHECKING:
    from ._bridge import CompiledSystem


def _pkg_name(system: "CompiledSystem") -> str:
    return f"mechanicsdsl_{system.name}"


_PACKAGE_XML = Template(
    """<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>$pkg</name>
  <version>0.1.0</version>
  <description>
    $system dynamics node generated by MechanicsDSL. Integrates the
    DSL-derived equations of motion and publishes generalized state.
  </description>
  <maintainer email="nomapa223@gmail.com">Noah Parsons</maintainer>
  <license>MIT</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <depend>rclcpp</depend>
  <depend>std_msgs</depend>

  <build_depend>rosidl_default_generators</build_depend>
  <exec_depend>rosidl_default_runtime</exec_depend>
  <member_of_group>rosidl_interface_packages</member_of_group>

  <test_depend>ament_lint_auto</test_depend>
  <test_depend>ament_lint_common</test_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""
)


_CMAKELISTS = Template(
    """cmake_minimum_required(VERSION 3.8)
project($pkg)

if(NOT CMAKE_CXX_STANDARD)
  set(CMAKE_CXX_STANDARD 17)
endif()

find_package(ament_cmake REQUIRED)
find_package(rclcpp REQUIRED)
find_package(std_msgs REQUIRED)
find_package(rosidl_default_generators REQUIRED)

rosidl_generate_interfaces($${PROJECT_NAME}
  "msg/SystemState.msg"
  DEPENDENCIES std_msgs
)

add_executable(${system}_node src/${system}_node.cpp)
target_include_directories(${system}_node PUBLIC
  $$<BUILD_INTERFACE:$${CMAKE_CURRENT_SOURCE_DIR}/include>
  $$<INSTALL_INTERFACE:include>)
ament_target_dependencies(${system}_node rclcpp std_msgs)

rosidl_get_typesupport_target(cpp_typesupport_target
  $${PROJECT_NAME} "rosidl_typesupport_cpp")
target_link_libraries(${system}_node "$${cpp_typesupport_target}")

install(TARGETS ${system}_node DESTINATION lib/$${PROJECT_NAME})
install(DIRECTORY launch config DESTINATION share/$${PROJECT_NAME})

ament_package()
"""
)


_SYSTEM_STATE_MSG = """# Generalized state of a MechanicsDSL system.
std_msgs/Header header
float64[] q          # generalized coordinates
float64[] q_dot      # generalized velocities
float64[] q_ddot     # generalized accelerations
float64   sim_time   # elapsed simulated time [s]
"""


_NODE_CPP = Template(
    """// Auto-generated by mechanicsdsl-ros2. DO NOT EDIT BY HAND.
#include <chrono>
#include <memory>
#include <vector>

#include "rclcpp/rclcpp.hpp"
#include "$pkg/${system}_dynamics.hpp"
#include "$pkg/msg/system_state.hpp"

using namespace std::chrono_literals;
using mechanicsdsl::$params_struct;
using SystemState = $pkg::msg::SystemState;

class ${cls}Node : public rclcpp::Node {
public:
  ${cls}Node() : Node("${system}_node") {
    const double rate_hz = this->declare_parameter<double>("rate_hz", $rate);
    dt_ = 1.0 / rate_hz;

$declare_params
$init_state
    pub_ = this->create_publisher<SystemState>("$system/state", 10);
    timer_ = this->create_wall_timer(
        std::chrono::duration<double>(dt_),
        std::bind(&${cls}Node::step, this));
    RCLCPP_INFO(this->get_logger(),
                "$system node up: %zu DOF @ %.1f Hz", N_, rate_hz);
  }

private:
  void step() {
    double qdd[N_ > 0 ? N_ : 1];
    mechanicsdsl::accel(y_.data(), y_.data() + N_, p_, qdd);
    mechanicsdsl::rk4_step(y_.data(), dt_, p_);
    sim_time_ += dt_;

    SystemState msg;
    msg.header.stamp = this->now();
    msg.q.assign(y_.begin(), y_.begin() + N_);
    msg.q_dot.assign(y_.begin() + N_, y_.end());
    msg.q_ddot.assign(qdd, qdd + N_);
    msg.sim_time = sim_time_;
    pub_->publish(msg);
  }

  static constexpr std::size_t N_ = $dof;
  $params_struct p_;
  std::vector<double> y_;
  double dt_{0.0};
  double sim_time_{0.0};
  rclcpp::Publisher<SystemState>::SharedPtr pub_;
  rclcpp::TimerBase::SharedPtr timer_;
};

int main(int argc, char** argv) {
  rclcpp::init(argc, argv);
  rclcpp::spin(std::make_shared<${cls}Node>());
  rclcpp::shutdown();
  return 0;
}
"""
)


_LAUNCH = Template(
    '''"""Launch the $system dynamics node."""
from launch import LaunchDescription
from launch_ros.actions import Node


def generate_launch_description():
    return LaunchDescription([
        Node(
            package="$pkg",
            executable="${system}_node",
            name="${system}_node",
            output="screen",
            parameters=["$${config}"] if False else [],
        ),
    ])
'''
)


def _render_declare_params(system: "CompiledSystem") -> str:
    lines = []
    for name in sorted(system.parameters):
        val = float(system.parameters[name])
        lines.append(
            f'    p_.{name} = this->declare_parameter<double>("{name}", {val!r});'
        )
    return "\n".join(lines)


def _render_init_state(system: "CompiledSystem") -> str:
    coords = system.coordinates
    n = len(coords)
    init = system.initial_conditions
    vals = []
    for c in coords:
        vals.append(repr(float(init.get(c, 0.0))))
    for c in coords:
        vals.append(repr(float(init.get(f"{c}_dot", 0.0))))
    joined = ", ".join(vals)
    return f"    y_ = {{{joined}}};  // [q..., q_dot...], {n} DOF"


def _render_params_yaml(system: "CompiledSystem") -> str:
    node = f"mechanicsdsl_{system.name}/{system.name}_node"
    lines = [f"{node}:", "  ros__parameters:", "    rate_hz: 250.0"]
    for name in sorted(system.parameters):
        lines.append(f"    {name}: {float(system.parameters[name])!r}")
    return "\n".join(lines) + "\n"


def scaffold_package(system: "CompiledSystem", out_dir: str) -> str:
    """Write a complete ROS2 package for ``system`` under ``out_dir``.

    Returns the path to the generated package directory.
    """
    pkg = _pkg_name(system)
    root = os.path.join(out_dir, pkg)
    include_dir = os.path.join(root, "include", pkg)
    for sub in ("src", "msg", "launch", "config", os.path.join("include", pkg)):
        os.makedirs(os.path.join(root, sub), exist_ok=True)

    cls = "".join(p.capitalize() for p in system.name.split("_"))
    subs = {
        "pkg": pkg,
        "system": system.name,
        "cls": cls,
        "dof": str(len(system.coordinates)),
        "rate": "250.0",
        "params_struct": params_struct_name(system),
        "declare_params": _render_declare_params(system),
        "init_state": _render_init_state(system),
    }

    guard = f"MECHANICSDSL_{system.name.upper()}_DYNAMICS_HPP"
    files = {
        os.path.join(root, "package.xml"): _PACKAGE_XML.substitute(subs),
        os.path.join(root, "CMakeLists.txt"): _CMAKELISTS.substitute(subs),
        os.path.join(include_dir, f"{system.name}_dynamics.hpp"):
            render_dynamics_header(system, guard),
        os.path.join(root, "src", f"{system.name}_node.cpp"):
            _NODE_CPP.substitute(subs),
        os.path.join(root, "msg", "SystemState.msg"): _SYSTEM_STATE_MSG,
        os.path.join(root, "launch", f"{system.name}.launch.py"):
            _LAUNCH.substitute(subs),
        os.path.join(root, "config", f"{system.name}_params.yaml"):
            _render_params_yaml(system),
    }
    for path, content in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    return root
