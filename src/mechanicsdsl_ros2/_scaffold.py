_SYSTEM_STATE_MSG = """# Generalized state of a MechanicsDSL system.
std_msgs/Header header
string[]  names      # coordinate names, in the order of the arrays below
float64[] q          # generalized coordinates
float64[] q_dot      # generalized velocities
float64[] q_ddot     # generalized accelerations
float64   energy     # E = sum(qdot dL/dqdot) - L (0 if no Lagrangian)
float64   energy_drift  # |E - E0| / |E0| since start or last reset
float64   sim_time   # elapsed simulated time [s]
"""


_NODE_CPP = Template(
    """// Auto-generated by mechanicsdsl-ros2. DO NOT EDIT BY HAND.
#include <algorithm>
#include <chrono>
#include <cmath>
#include <memory>
#include <string>
#include <vector>

#include "rclcpp/rclcpp.hpp"
#include "sensor_msgs/msg/joint_state.hpp"
#include "std_srvs/srv/trigger.hpp"
#include "$pkg/${system}_dynamics.hpp"
#include "$pkg/msg/system_state.hpp"

using mechanicsdsl::$params_struct;
using SystemState = $pkg::msg::SystemState;
using JointState = sensor_msgs::msg::JointState;
using Trigger = std_srvs::srv::Trigger;

class ${cls}Node : public rclcpp::Node {
public:
  ${cls}Node() : Node("${system}_node") {
    const double rate_hz = this->declare_parameter<double>("rate_hz", $rate);
    dt_ = 1.0 / rate_hz;
    substeps_ = this->declare_parameter<int>("substeps", 1);
    paused_ = this->declare_parameter<bool>("paused", false);

$declare_params
    reset();

    param_cb_ = this->add_on_set_parameters_callback(
        [this](const std::vector<rclcpp::Parameter>& params) {
          rcl_interfaces::msg::SetParametersResult result;
          result.successful = true;
          for (const auto& prm : params) {
            const auto& n = prm.get_name();
            if (n == "paused") { paused_ = prm.as_bool(); }
            else if (n == "substeps") {
              if (prm.as_int() < 1) { result.successful = false; result.reason = "substeps >= 1"; }
              else { substeps_ = prm.as_int(); }
            }
$param_updates
          }
          return result;
        });

    state_pub_ = this->create_publisher<SystemState>("$system/state", 10);
    joint_pub_ = this->create_publisher<JointState>("$system/joint_states", 10);
    reset_srv_ = this->create_service<Trigger>(
        "$system/reset",
        [this](const std::shared_ptr<Trigger::Request>, std::shared_ptr<Trigger::Response> res) {
          reset();
          res->success = true;
          res->message = "state reset to DSL initial conditions";
        });
    timer_ = this->create_wall_timer(
        std::chrono::duration<double>(dt_), std::bind(&${cls}Node::step, this));
    RCLCPP_INFO(this->get_logger(), "$system node up: %zu DOF @ %.1f Hz", N_, rate_hz);
  }

private:
  double energy() const {
    return $energy_expr;
  }

  void reset() {
    mechanicsdsl::initial_state(y_.data(), p_);
    sim_time_ = 0.0;
    energy0_ = energy();
  }

  void step() {
    if (paused_) { return; }
    const int n = std::max<int>(1, static_cast<int>(substeps_));
    for (int i = 0; i < n; ++i) { mechanicsdsl::rk4_step(y_.data(), dt_ / n, p_); }
    sim_time_ += dt_;

    double qdd[N_];
    mechanicsdsl::accel(y_.data(), y_.data() + N_, p_, qdd);
    const double e = energy();
    const auto stamp = this->now();

    SystemState msg;
    msg.header.stamp = stamp;
    msg.names = names_;
    msg.q.assign(y_.begin(), y_.begin() + N_);
    msg.q_dot.assign(y_.begin() + N_, y_.end());
    msg.q_ddot.assign(qdd, qdd + N_);
    msg.energy = e;
    msg.energy_drift = std::fabs(e - energy0_) / std::max(std::fabs(energy0_), 1e-12);
    msg.sim_time = sim_time_;
    state_pub_->publish(msg);

    JointState js;
    js.header.stamp = stamp;
    js.name = names_;
    js.position.assign(y_.begin(), y_.begin() + N_);
    js.velocity.assign(y_.begin() + N_, y_.end());
    joint_pub_->publish(js);
  }

  static constexpr std::size_t N_ = $dof;
  const std::vector<std::string> names_{$names};
  $params_struct p_;
  std::vector<double> y_ = std::vector<double>(2 * N_, 0.0);
  double dt_{0.0};
  double sim_time_{0.0};
  double energy0_{0.0};
  int64_t substeps_{1};
  bool paused_{false};
  rclcpp::Publisher<SystemState>::SharedPtr state_pub_;
  rclcpp::Publisher<JointState>::SharedPtr joint_pub_;
  rclcpp::Service<Trigger>::SharedPtr reset_srv_;
  rclcpp::TimerBase::SharedPtr timer_;
  rclcpp::node_interfaces::OnSetParametersCallbackHandle::SharedPtr param_cb_;
};

int main(int argc, char** argv) {
  rclcpp::init(argc, argv);
  rclcpp::spin(std::make_shared<${cls}Node>());
  rclcpp::shutdown();
  return 0;
}
"""
)


