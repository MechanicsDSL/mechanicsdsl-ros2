"""
_pyscaffold.py
--------------
Generate a pure-Python ROS2 (``ament_python`` / rclpy) package.

No compiler, no custom messages: the package builds in seconds with
``colcon build`` and runs anywhere ``rclpy`` does, which makes it the quickest
way to drop a DSL system into an existing ROS2 graph. Layout::

    mechanicsdsl_<system>_py/
      package.xml, setup.py, setup.cfg, resource/<pkg>
      <pkg>/__init__.py
      <pkg>/dynamics.py     (pure Python, stdlib math only: PARAMS, accel, rk4_step, energy)
      <pkg>/node.py         (rclpy node)
      launch/<system>.launch.py, config/<system>_params.yaml

The node publishes ``sensor_msgs/JointState`` on ``<system>/joint_states``
and ``std_msgs/Float64`` energy on ``<system>/energy``, accepts live parameter
updates, and offers a ``<system>/reset`` ``std_srvs/Trigger`` service.

``dynamics.py`` has no ROS dependency, so it is imported and checked
numerically by this package's own test suite.
"""

from __future__ import annotations

import os
from typing import TYPE_CHECKING, Dict

import sympy as sp
from sympy.printing.pycode import PythonCodePrinter

from ._scaffold import render_launch, render_params_yaml

if TYPE_CHECKING:
    from ._bridge import CompiledSystem


def py_pkg_name(system: "CompiledSystem") -> str:
    return f"mechanicsdsl_{system.name}_py"


def render_dynamics_py(system: "CompiledSystem") -> str:
    """Pure-Python dynamics module (stdlib ``math`` only)."""
    pr = PythonCodePrinter({"fully_qualified_modules": True})
    n = system.dof
    params = sorted(system.parameters)

    def bind(used, ysrc_q, ysrc_qd):
        out = []
        for i, c in enumerate(system.coordinates):
            if c in used:
                out.append(f"    {c} = {ysrc_q}[{i}]")
            if f"{c}_dot" in used:
                out.append(f"    {c}_dot = {ysrc_qd}[{i}]")
        for p in params:
            if p in used:
                out.append(f"    {p} = mdsl_params[{p!r}]")
        return out

    exprs = [system.equations[f"{c}_ddot"] for c in system.coordinates]
    used = set().union(*[{str(s) for s in e.free_symbols} for e in exprs])
    temps, reduced = sp.cse(exprs, symbols=sp.numbered_symbols("_t"))
    accel = "\n".join(bind(used, "mdsl_q", "mdsl_qd")
                      + [f"    {s} = {pr.doprint(v)}" for s, v in temps]
                      + [f"    return [{', '.join(pr.doprint(e) for e in reduced)}]"])

    if system.energy is not None:
        e_used = {str(s) for s in system.energy.free_symbols}
        e_temps, (e_red,) = sp.cse([system.energy], symbols=sp.numbered_symbols("_e"))
        energy = "\n".join(bind(e_used, "mdsl_y", f"mdsl_y[{n}:]")
                           + [f"    {s} = {pr.doprint(v)}" for s, v in e_temps]
                           + [f"    return {pr.doprint(e_red)}"])
    else:
        energy = "    return 0.0"

    defaults = ",\n".join(f"    {p!r}: {float(system.parameters[p])!r}" for p in params)
    src = "\n".join(f"#     {ln}" for ln in system.source.splitlines())
    return f'''\
# Auto-generated by mechanicsdsl-ros2. DO NOT EDIT BY HAND.
#
# Dynamics derived by mechanicsdsl-core from:
#
{src}
#
"""Pure-Python {system.name} dynamics (stdlib math only; no ROS dependency)."""
import math  # noqa: F401  (used by the generated expressions)

DOF = {n}
STATE_DIM = {2 * n}
COORDINATES = {list(system.coordinates)!r}
STATE_NAMES = {list(system.state_names)!r}
PARAMS = {{
{defaults}
}}
INITIAL_STATE = {list(system.initial_state())!r}


def accel(mdsl_q, mdsl_qd, mdsl_params=PARAMS):
    """Generalized accelerations from positions q and velocities qd."""
{accel}


def deriv(y, params=PARAMS):
    qdd = accel(y[:DOF], y[DOF:], params)
    return list(y[DOF:]) + list(qdd)


def rk4_step(y, dt, params=PARAMS):
    """Return the state after one classic RK4 step of size dt."""
    k1 = deriv(y, params)
    k2 = deriv([a + 0.5 * dt * b for a, b in zip(y, k1)], params)
    k3 = deriv([a + 0.5 * dt * b for a, b in zip(y, k2)], params)
    k4 = deriv([a + dt * b for a, b in zip(y, k3)], params)
    return [a + dt / 6.0 * (b1 + 2.0 * b2 + 2.0 * b3 + b4)
            for a, b1, b2, b3, b4 in zip(y, k1, k2, k3, k4)]


def energy(mdsl_y, mdsl_params=PARAMS):
    """Jacobi energy E = sum(qdot dL/dqdot) - L."""
{energy}
'''


_NODE_PY = '''\
# Auto-generated by mechanicsdsl-ros2. DO NOT EDIT BY HAND.
"""rclpy node integrating the @SYSTEM@ dynamics."""
import rclpy
from rcl_interfaces.msg import SetParametersResult
from rclpy.node import Node
from sensor_msgs.msg import JointState
from std_msgs.msg import Float64
from std_srvs.srv import Trigger

from . import dynamics


class DynamicsNode(Node):
    def __init__(self):
        super().__init__("@SYSTEM@_node")
        rate_hz = self.declare_parameter("rate_hz", 250.0).value
        self.dt = 1.0 / rate_hz
        self.substeps = int(self.declare_parameter("substeps", 1).value)
        self.paused = bool(self.declare_parameter("paused", False).value)
        self.params = {
            name: float(self.declare_parameter(name, value).value)
            for name, value in dynamics.PARAMS.items()
        }
        self.add_on_set_parameters_callback(self._on_params)
        self.joint_pub = self.create_publisher(JointState, "@SYSTEM@/joint_states", 10)
        self.energy_pub = self.create_publisher(Float64, "@SYSTEM@/energy", 10)
        self.create_service(Trigger, "@SYSTEM@/reset", self._on_reset)
        self.reset()
        self.create_timer(self.dt, self.step)
        self.get_logger().info(
            f"@SYSTEM@ node up: {dynamics.DOF} DOF @ {rate_hz:.1f} Hz")

    def reset(self):
        self.y = list(dynamics.INITIAL_STATE)
        self.sim_time = 0.0

    def _on_reset(self, request, response):
        self.reset()
        response.success = True
        response.message = "state reset to DSL initial conditions"
        return response

    def _on_params(self, params):
        for p in params:
            if p.name == "paused":
                self.paused = bool(p.value)
            elif p.name == "substeps":
                if int(p.value) < 1:
                    return SetParametersResult(successful=False, reason="substeps >= 1")
                self.substeps = int(p.value)
            elif p.name in self.params:
                self.params[p.name] = float(p.value)
        return SetParametersResult(successful=True)

    def step(self):
        if self.paused:
            return
        h = self.dt / self.substeps
        for _ in range(self.substeps):
            self.y = dynamics.rk4_step(self.y, h, self.params)
        self.sim_time += self.dt
        js = JointState()
        js.header.stamp = self.get_clock().now().to_msg()
        js.name = list(dynamics.COORDINATES)
        js.position = self.y[:dynamics.DOF]
        js.velocity = self.y[dynamics.DOF:]
        self.joint_pub.publish(js)
        self.energy_pub.publish(Float64(data=float(dynamics.energy(self.y, self.params))))


def main(args=None):
    rclpy.init(args=args)
    node = DynamicsNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
'''


def render_python_package(system: "CompiledSystem", rate_hz: float = 250.0) -> Dict[str, str]:
    """Return ``{relative_path: text}`` for the ament_python package."""
    pkg = py_pkg_name(system)
    sysn = system.name
    package_xml = f"""<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>{pkg}</name>
  <version>0.1.0</version>
  <description>{sysn} dynamics (pure Python) generated by MechanicsDSL.</description>
  <maintainer email="nomapa223@gmail.com">Noah Parsons</maintainer>
  <license>MIT</license>

  <exec_depend>rclpy</exec_depend>
  <exec_depend>std_msgs</exec_depend>
  <exec_depend>sensor_msgs</exec_depend>
  <exec_depend>std_srvs</exec_depend>
  <exec_depend>rcl_interfaces</exec_depend>
  <exec_depend>launch_ros</exec_depend>

  <test_depend>python3-pytest</test_depend>

  <export>
    <build_type>ament_python</build_type>
  </export>
</package>
"""
    setup_py = f'''from glob import glob

from setuptools import setup

package_name = "{pkg}"

setup(
    name=package_name,
    version="0.1.0",
    packages=[package_name],
    data_files=[
        ("share/ament_index/resource_index/packages", ["resource/" + package_name]),
        ("share/" + package_name, ["package.xml"]),
        ("share/" + package_name + "/launch", glob("launch/*.launch.py")),
        ("share/" + package_name + "/config", glob("config/*.yaml")),
    ],
    install_requires=["setuptools"],
    zip_safe=True,
    description="{sysn} dynamics generated by MechanicsDSL",
    license="MIT",
    tests_require=["pytest"],
    entry_points={{"console_scripts": ["{sysn}_node = {pkg}.node:main"]}},
)
'''
    setup_cfg = f"""[develop]
script_dir=$base/lib/{pkg}
[install]
install_scripts=$base/lib/{pkg}
"""
    return {
        "package.xml": package_xml,
        "setup.py": setup_py,
        "setup.cfg": setup_cfg,
        os.path.join("resource", pkg): "",
        os.path.join(pkg, "__init__.py"): "",
        os.path.join(pkg, "dynamics.py"): render_dynamics_py(system),
        os.path.join(pkg, "node.py"): _NODE_PY.replace("@SYSTEM@", sysn),
        os.path.join("launch", f"{sysn}.launch.py"): render_launch(system, pkg, f"{sysn}_node"),
        os.path.join("config", f"{sysn}_params.yaml"): render_params_yaml(system, rate_hz),
    }


def scaffold_python_package(system: "CompiledSystem", out_dir: str,
                            rate_hz: float = 250.0) -> str:
    """Write the ament_python package under ``out_dir``; return its root."""
    root = os.path.join(out_dir, py_pkg_name(system))
    for rel, text in render_python_package(system, rate_hz).items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return root
